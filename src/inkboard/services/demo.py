"""A deterministic synthetic pen recording: a circle, a square, a wave and a triangle.

Shapes are laid out on the portrait page and converted to raw digitizer units through the
default orientation, so the demo draws upright with default settings. No randomness and
fixed timestamps, so the committed fixture can be regenerated byte for byte.
"""

import math

from inkboard.core.config import Settings
from inkboard.services.events import (
    ABS_DISTANCE,
    ABS_PRESSURE,
    ABS_X,
    ABS_Y,
    BTN_TOOL_PEN,
    BTN_TOUCH,
    EV_ABS,
    EV_KEY,
    EV_SYN,
    SYN_REPORT,
    InputEvent,
    encode_event,
)
from inkboard.services.geometry import Orientation, to_raw

PAGE_ASPECT = 1404 / 1872  # width / height of the portrait page
STEP_US = 5_000  # 200 samples per second
GAP_US = 400_000  # pen lifted between shapes
START_SEC = 1000
# The settings default, read from the one place it is defined.
DEFAULT_ORIENTATION = Orientation.parse(Settings.model_fields["orientation"].default)


def _circle(cu: float, cv: float, r: float, n: int = 90) -> list[tuple[float, float]]:
    return [
        (cu + r * math.cos(t), cv + r * math.sin(t) * PAGE_ASPECT) for t in (2 * math.pi * i / n for i in range(n + 1))
    ]


def _polyline(points: list[tuple[float, float]], per_edge: int = 30) -> list[tuple[float, float]]:
    out: list[tuple[float, float]] = []
    for (u0, v0), (u1, v1) in zip(points, points[1:], strict=False):
        out += [(u0 + (u1 - u0) * i / per_edge, v0 + (v1 - v0) * i / per_edge) for i in range(per_edge)]
    out.append(points[-1])
    return out


def shapes() -> list[list[tuple[float, float]]]:
    square = [(0.58, 0.14), (0.86, 0.14), (0.86, 0.35), (0.58, 0.35), (0.58, 0.14)]
    wave = [(0.12 + 0.76 * i / 120, 0.55 + 0.05 * math.sin(i / 120 * 4 * math.pi)) for i in range(121)]
    triangle = [(0.5, 0.68), (0.72, 0.9), (0.28, 0.9), (0.5, 0.68)]
    return [_circle(0.27, 0.245, 0.14), _polyline(square), wave, _polyline(triangle)]


def generate(orientation: Orientation = DEFAULT_ORIENTATION) -> list[InputEvent]:
    clock_us = 0
    events: list[InputEvent] = []

    def emit(ev_type: int, code: int, value: int) -> None:
        events.append(InputEvent(START_SEC + clock_us // 1_000_000, clock_us % 1_000_000, ev_type, code, value))

    def report() -> None:
        nonlocal clock_us
        emit(EV_SYN, SYN_REPORT, 0)
        clock_us += STEP_US

    emit(EV_KEY, BTN_TOOL_PEN, 1)
    emit(EV_ABS, ABS_DISTANCE, 40)
    report()
    for stroke in shapes():
        for index, (u, v) in enumerate(stroke):
            x, y = to_raw(u, v, orientation)
            pressure = round(2200 + 1400 * math.sin(math.pi * index / max(1, len(stroke) - 1)))
            if index == 0:
                emit(EV_KEY, BTN_TOUCH, 1)
            emit(EV_ABS, ABS_X, x)
            emit(EV_ABS, ABS_Y, y)
            emit(EV_ABS, ABS_PRESSURE, pressure)
            if index == 0:
                emit(EV_ABS, ABS_DISTANCE, 0)
            report()
        emit(EV_KEY, BTN_TOUCH, 0)
        emit(EV_ABS, ABS_PRESSURE, 0)
        emit(EV_ABS, ABS_DISTANCE, 20)
        report()
        clock_us += GAP_US
    emit(EV_KEY, BTN_TOOL_PEN, 0)
    report()
    return events


def generate_bytes(event_size: int = 16) -> bytes:
    return b"".join(encode_event(event, event_size) for event in generate())
